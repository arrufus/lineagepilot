"""Write docs/rules.md from the built-in rules; diagnostics link to its sections.

Usage, from packages/core:

    uv run python scripts/rules_doc.py           write it
    uv run python scripts/rules_doc.py --check   fail if it is out of date (a test runs this)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from lineagepilot_core.rules import builtin_rules

DOC = Path(__file__).resolve().parents[3] / "docs" / "rules.md"

INTRO = """\
# LineagePilot rules

LineagePilot checks every dbt node against these rules and shows the results in the
Problems panel. Each diagnostic links to its rule below.

Every check has one of five results: **pass**, **fail**, **not applicable**,
**unsupported** (LineagePilot cannot make this check) or **unknown** (the facts it needs
are missing, for example column lineage). Failures are shown with the rule's severity;
unknown results are shown as information ("Not checked"), never as passes. The score
counts only passes and failures, and coverage, shown beside it, says how much could be
checked.

PII rules report *indicators*, from tags, column names and lineage, not verified
exposure.

Add, disable or re-grade rules in `.lineagepilot/rules.yml` at the project root. Custom
rules are not loaded in Restricted Mode.

This file is generated by `packages/core/scripts/rules_doc.py`.
"""


def render() -> str:
    parts = [INTRO]
    for rule in builtin_rules():
        kinds = ", ".join(sorted(k.value for k in rule.resource_types))
        lines = [
            f"### {rule.id}",
            "",
            f"**{rule.name}**. {rule.description}",
            "",
            f"- Severity: {rule.severity.value}",
            f"- Category: {rule.category.value}",
            f"- Checks: each {'column of each ' if rule.scope.value == 'column' else ''}{kinds}",
        ]
        if rule.remediation:
            lines.append(f"- Fix: {rule.remediation}")
        if rule.replaces:
            lines.append(f"- Replaces the Data Capsule rule: {rule.replaces}")
        parts.append("\n".join(lines) + "\n")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    current = DOC.read_text(encoding="utf-8") if DOC.is_file() else None
    if current == text:
        return 0
    if args.check:
        sys.stderr.write(f"{DOC} is out of date; run scripts/rules_doc.py\n")
        return 1
    DOC.write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.write(f"wrote {DOC}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
